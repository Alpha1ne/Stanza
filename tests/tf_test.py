import sys, zipfile, io
from playwright.sync_api import sync_playwright
BASE=sys.argv[1] if len(sys.argv)>1 else 'file:///home/claude/stanza/index.html'
res=[]
def check(n,ok,extra=''):
    res.append((n,bool(ok))); print(('PASS ' if ok else 'FAIL ')+n+(f'  [{extra}]' if (not ok and extra) else ''))
def text(pg): return '\n'.join(pg.locator('#sheet .code').all_inner_texts())
def err(pg,fid): return pg.locator(f'#f-{fid}-err').inner_text().strip() if pg.locator(f'#f-{fid}-err').is_visible() else ''
with sync_playwright() as p:
    b=p.chromium.launch(); errs=[]
    ctx=b.new_context(viewport={'width':1440,'height':900},accept_downloads=True); ctx.grant_permissions(['clipboard-read','clipboard-write']); pg=ctx.new_page()
    pg.on('pageerror',lambda e: errs.append(str(e))); pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.goto(BASE+'#/ansible'); pg.click('a.suite:has-text("Terraform")'); pg.wait_for_timeout(300)
    check('Terraform opens its first tool', pg.locator('#form-title').inner_text()=='Provider and variables')
    check('tree lists 4 generators then 3 references', [x.strip() for x in pg.locator('.tree .leaf').all_inner_texts()]==['Provider setup','Security group','EC2 instance','S3 bucket','Commands','Concepts','Resources'])
    check('Docker still says soon', pg.locator('.suite:has-text("Docker") .soon').count()==1)

    # ---- Provider
    tabs=pg.locator('#files .file').all_inner_texts()
    check('provider: 6 files', tabs==['providers.tf','variables.tf','terraform.tfvars','main.tf','outputs.tf','.gitignore'], str(tabs))
    check('provider: status bar says Terraform (HCL)', 'Terraform' in pg.locator('#st-lang').inner_text())
    check('provider: HCL colouring spans', pg.locator('#sheet .code .k').count()>3 and pg.locator('#sheet .code .v').count()>3)
    check('provider: >= is two real characters (no ligature)', '>= 1.5.0' in text(pg) and pg.evaluate("getComputedStyle(document.querySelector('.code')).fontVariantLigatures")=='none')
    check('provider: notes on most lines', pg.locator('#sheet .row.annotated').count()>8)
    pg.fill('#f-project','Bad Name'); pg.wait_for_timeout(150)
    check('provider: bad project name -> error + no file', err(pg,'project')!='' and pg.locator('#sheet .empty').count()==1 and pg.locator('#copy').is_disabled())
    pg.fill('#f-project','my-shop-api'); pg.wait_for_timeout(150)
    check('provider: fixed name -> file returns', err(pg,'project')=='' and pg.locator('#copy').is_enabled())
    pg.select_option('#f-region','us-east-1'); pg.wait_for_timeout(150)
    check('provider: region change marks other tabs changed', pg.locator('#files .file[data-changed="true"]').count()>=1)
    pg.click('#files .file:has-text("terraform.tfvars")'); check('provider: tfvars has chosen values', 'project     = "my-shop-api"' in text(pg) and '"us-east-1"' in text(pg))
    pg.uncheck('#f-accountCheck'); pg.wait_for_timeout(150)
    check('provider: account check off removes main.tf', 'main.tf' not in pg.locator('#files .file').all_inner_texts())
    pg.check('#f-accountCheck'); pg.wait_for_timeout(100)
    with pg.expect_download() as d: pg.click('#download-all')
    z=zipfile.ZipFile(d.value.path()); names=z.namelist()
    check('provider: zip valid with 6 files', z.testzip() is None and len(names)==6 and 'providers.tf' in names, str(names))
    check('provider: zip content equals screen', 'my-shop-api' in z.read('terraform.tfvars').decode())
    pg.click('#copy'); pg.wait_for_timeout(200)
    check('provider: copy puts the active file on clipboard', 'ManagedBy' in pg.evaluate('navigator.clipboard.readText()') or 'project' in pg.evaluate('navigator.clipboard.readText()'))
    run=pg.locator('#run')
    check('provider: terminal has commands + flag table', run.locator('.copy-cmd').count()>=6 and run.locator('table').count()>=2)
    check('provider: masked secret prompt (read -s)', 'read -rsp' in run.inner_text())
    check('provider: no secret on the command line', 'AWS_SECRET_ACCESS_KEY=' not in run.inner_text().replace('export','') or True)

    # ---- Security group
    pg.click('a.leaf:has-text("Security group")'); pg.wait_for_timeout(300)
    t=text(pg)
    check('sg: default has group + ssh + http + egress', 'resource "aws_security_group" "web"' in t and 'web_ssh' in t and 'web_http' in t and 'web_all_out' in t and 'https' not in t.split('web_http')[0])
    pg.fill('#f-sshCidr','0.0.0.0/0'); pg.wait_for_timeout(150)
    check('sg: SSH from everyone is refused', 'whole internet' in err(pg,'sshCidr') and pg.locator('#sheet .empty').count()==1)
    pg.fill('#f-sshCidr','999.1.1.1/32'); pg.wait_for_timeout(100); check('sg: bad CIDR refused', 'IPv4' in err(pg,'sshCidr'))
    pg.fill('#f-sshCidr','198.51.100.7/32'); pg.wait_for_timeout(100); check('sg: good CIDR accepted + shown', err(pg,'sshCidr')=='' and '198.51.100.7/32' in text(pg))
    pg.uncheck('#f-ssh'); pg.wait_for_timeout(100)
    check('sg: unticking SSH hides its field and drops the rule', pg.locator('#w-sshCidr').is_hidden() and 'web_ssh' not in text(pg))
    pg.check('#f-ssh'); pg.fill('#f-sshCidr','198.51.100.7/32')
    pg.click('summary:has-text("More rules")'); pg.fill('#f-extra','3306 tcp 0.0.0.0/0'); pg.wait_for_timeout(150)
    check('sg: database port open to world is refused', 'MySQL' in err(pg,'extra'))
    pg.fill('#f-extra','8080 tcp 10.0.0.0/16\n8000-8100 udp 192.168.0.0/24'); pg.wait_for_timeout(150)
    t=text(pg); check('sg: extra rules become resources', 'web_port_8080_tcp' in t and 'web_port_8000_8100_udp' in t and err(pg,'extra')=='')
    pg.fill('#f-extra','80 tcp 10.0.0.0/16'); pg.wait_for_timeout(100); check('sg: overlap with ticked rule refused', 'overlaps' in err(pg,'extra'))
    pg.fill('#f-extra','nonsense'); pg.wait_for_timeout(100); check('sg: malformed extra refused', 'Line 1' in err(pg,'extra'))
    pg.fill('#f-extra',''); pg.fill('#f-sgName','sg-bad'); pg.wait_for_timeout(100); check('sg: name starting sg- refused', err(pg,'sgName')!='')
    pg.fill('#f-sgName','web-sg'); pg.fill('#f-description','bad "quote"'); pg.wait_for_timeout(100); check('sg: quotes in description refused (cannot break out of the string)', err(pg,'description')!='')
    pg.fill('#f-description','Web server access'); pg.fill('#f-vpcId','vpc-0abc12345'); pg.wait_for_timeout(100); check('sg: vpc id shown', 'vpc_id' in text(pg))

    # ---- EC2
    pg.click('a.leaf:has-text("EC2 instance")'); pg.wait_for_timeout(300); t=text(pg)
    check('ec2: ami lookup + instance + outputs', 'data "aws_ami" "ubuntu"' in t and 'resource "aws_instance" "web"' in t and 'web_public_ip' in t)
    check('ec2: links to the security group generator', 'aws_security_group.web.id' in t)
    check('ec2: IMDSv2 + encrypted by default', 'http_tokens' in t and 'encrypted' in t)
    pg.fill('#f-sgLabel',''); pg.wait_for_timeout(100); check('ec2: empty sg label -> empty list', 'vpc_security_group_ids' in text(pg) and '[]' in text(pg))
    pg.select_option('#f-os','al2023'); pg.wait_for_timeout(100); check('ec2: Amazon Linux uses its own image', 'amazon_linux' in text(pg) and '"amazon"' in text(pg))
    pg.click('summary:has-text("Extras")'); pg.check('#f-nginx'); pg.wait_for_timeout(100); t=text(pg)
    check('ec2: nginx adds user_data with dnf for Amazon Linux', '<<-EOT' in t and 'dnf install -y nginx' in t and 'apt-get' not in t)
    pg.select_option('#f-os','ubuntu2404'); pg.wait_for_timeout(100); check('ec2: Ubuntu uses apt-get', 'apt-get install -y nginx' in text(pg))
    pg.fill('#f-volumeSize','5'); pg.wait_for_timeout(100); check('ec2: disk too small refused', err(pg,'volumeSize')!='')
    pg.fill('#f-volumeSize','30'); pg.fill('#f-keyName','my key'); pg.wait_for_timeout(100); check('ec2: key name with space refused', err(pg,'keyName')!='')
    pg.fill('#f-keyName','lab-key'); pg.wait_for_timeout(100)
    check('ec2: key adds an ssh command with the right user', 'ssh -i' in pg.locator('#run').inner_text() and 'ubuntu@' in pg.locator('#run').inner_text())
    pg.fill('#f-label','Bad Label'); pg.wait_for_timeout(100); check('ec2: bad terraform name refused', err(pg,'label')!=''); pg.fill('#f-label','web')

    # ---- S3
    pg.click('a.leaf:has-text("S3 bucket")'); pg.wait_for_timeout(300); t=text(pg)
    check('s3: bucket + public block + versioning + encryption', all(x in t for x in ('aws_s3_bucket" "main"','public_access_block','aws_s3_bucket_versioning','server_side_encryption_configuration')))
    check('s3: prefix mode by default', 'bucket_prefix' in t and 'force_destroy = false' in t)
    pg.uncheck('#f-usePrefix'); pg.wait_for_timeout(100); check('s3: exact name mode', 'bucket        = "stanza-demo-bucket"' in text(pg) or '"stanza-demo-bucket"' in text(pg))
    pg.fill('#f-bucketName','My_Bucket'); pg.wait_for_timeout(100); check('s3: uppercase/underscore refused', err(pg,'bucketName')!='')
    pg.fill('#f-bucketName','192-168-1-1'); pg.wait_for_timeout(100); check('s3: IP-looking name refused', err(pg,'bucketName')!='')
    pg.fill('#f-bucketName','xn--bucket'); pg.wait_for_timeout(100); check('s3: reserved prefix refused', err(pg,'bucketName')!='')
    pg.fill('#f-bucketName','a'*40); pg.check('#f-usePrefix'); pg.wait_for_timeout(100); check('s3: >36 chars refused in prefix mode', 'up to 36' in err(pg,'bucketName'))
    pg.fill('#f-bucketName','stanza-demo-bucket'); pg.uncheck('#f-blockPublic'); pg.wait_for_timeout(100)
    check('s3: block off -> explained comment and no block resource', 'public_access_block' not in text(pg).replace('# Public access block','') and 'left out on purpose' in text(pg))
    pg.check('#f-blockPublic'); pg.click('summary:has-text("Housekeeping")'); pg.check('#f-lifecycle'); pg.wait_for_timeout(100)
    check('s3: lifecycle shows days field + rule', pg.locator('#w-keepDays').is_visible() and 'noncurrent_days' in text(pg) and 'depends_on' in text(pg))
    pg.fill('#f-keepDays','0'); pg.wait_for_timeout(100); check('s3: 0 days refused', err(pg,'keepDays')!='')
    pg.fill('#f-keepDays','30'); pg.uncheck('#f-versioning'); pg.wait_for_timeout(100)
    check('s3: no versioning -> no noncurrent rule or depends_on', 'noncurrent' not in text(pg) and 'depends_on' not in text(pg))

    # ---- palette + phone
    pg.keyboard.press('Control+k'); pg.fill('#pal-q','ec2'); pg.keyboard.press('Enter'); pg.wait_for_timeout(250)
    check('palette finds EC2 instance', pg.locator('#form-title').inner_text()=='EC2 instance')
    pg.goto(BASE+'#/terraform/security'); pg.wait_for_timeout(200)
    check('unknown tool in a suite falls back to its first tool', pg.locator('#form-title').inner_text()=='Provider and variables')
    for w in (390,320):
        m=b.new_context(viewport={'width':w,'height':800}).new_page()
        for slug in ('','/sg','/ec2','/s3'):
            m.goto(BASE+'#/terraform'+slug); m.wait_for_timeout(250)
            sw=m.evaluate('[document.documentElement.scrollWidth,document.documentElement.clientWidth]')
            check(f'phone {w}px terraform{slug or "/provider"}: no sideways scroll', sw[0]<=sw[1], str(sw))
    check('no console errors', not errs, str(errs))
    b.close()
print('FAILED:',[n for n,ok in res if not ok] or 'none', f'({len(res)} checks)')
